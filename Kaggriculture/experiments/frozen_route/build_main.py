"""Generates a self-contained, Kaggle-submittable main.py from a frozen
action list: embeds the actions as a plain JSON literal (no need to
obfuscate our own code the way opponents/submission_27 does) plus the
weed-repair replay logic from freeze.py.
"""
from __future__ import annotations

import json

TEMPLATE = '''"""Kaggriculture submission -- frozen 720-step route.

Generated by experiments/frozen_route/build_main.py from a recorded
trajectory of {source_desc}. Actions are replayed by step index; a
weed-repair layer digs out and retries any PLANT/BUILD_PASTURE that
lands on a weed this specific game spawned that the recording didn't
(weeds are random per game, see game/README.md), then spends a bounded
catch-up window replaying each one-step-earlier recorded action so the
actor re-syncs to the script's step index instead of drifting out of
position for the rest of the game. Do not hand-edit; regenerate via
build_main.py.
"""
from __future__ import annotations

import copy
import json as _json

_ACTIONS = _json.loads({actions_json!r})

WEED_REPLAY_STEPS = 8
_WEED_STATE = {{0: {{}}, 1: {{}}}}


def _copy_action(action):
    action = copy.deepcopy(action or {{}})
    return {{
        "farmer": list(action.get("farmer") or ["PASS"]),
        "hands": [list(op or ["PASS"]) for op in (action.get("hands") or [])],
        "market": [list(order) for order in (action.get("market") or [])],
    }}


def _align_hands(action, expected):
    hands = list(action.get("hands") or [])
    if len(hands) < expected:
        hands = hands + [["PASS"] for _ in range(expected - len(hands))]
    action["hands"] = [list(op or ["PASS"]) for op in hands[:expected]]
    return action


def _tile_at(farm, pos):
    try:
        x, y = int(pos[0]), int(pos[1])
        return farm["tiles"][y][x]
    except (IndexError, TypeError, ValueError):
        return "LOCKED"


def _trace_actor_action(step, actor):
    trace = _ACTIONS[min(max(int(step), 0), len(_ACTIONS) - 1)] or {{}}
    if actor == "farmer":
        return list(trace.get("farmer") or ["PASS"])
    hands = trace.get("hands", []) or []
    return list(hands[actor] if actor < len(hands) else ["PASS"])


def _repair(observation, action, step):
    seat = 1 if int(observation.get("player", 0) or 0) == 1 else 0
    game = _WEED_STATE[seat]
    if step == 0 or step < game.get("last_step", -1):
        game = {{"last_step": step, "active": {{}}}}
        _WEED_STATE[seat] = game
    game["last_step"] = step

    farms = observation.get("farms", []) or []
    farm = farms[seat] if seat < len(farms) else {{}}
    positions = [farm.get("farmer"), *(farm.get("hands") or [])]
    ops = [action.get("farmer", ["PASS"]), *(action.get("hands") or [])]
    active = game["active"]

    for actor, pending in list(active.items()):
        index = 0 if actor == "farmer" else int(actor) + 1
        if index >= len(ops):
            active.pop(actor, None)
            continue
        age = step - pending["start"]
        if age == 1:
            ops[index] = list(pending["intended"])
        elif 2 <= age <= 1 + WEED_REPLAY_STEPS:
            ops[index] = _trace_actor_action(step - 1, actor)
        else:
            active.pop(actor, None)

    for index, (pos, op) in enumerate(zip(positions, ops)):
        actor = "farmer" if index == 0 else index - 1
        if actor in active or not isinstance(op, list) or not op:
            continue
        if op[0] not in ("PLANT", "BUILD_PASTURE"):
            continue
        tile = _tile_at(farm, pos)
        if not (isinstance(tile, dict) and tile.get("kind") == "WEED"):
            continue
        active[actor] = {{"start": step, "intended": list(op)}}
        ops[index] = ["DIG"]

    action["farmer"] = ops[0] if ops else ["PASS"]
    action["hands"] = ops[1:]
    return action


def agent(observation):
    try:
        step = min(max(0, int(observation.get("step", 0) or 0)), len(_ACTIONS) - 1)
        action = _copy_action(_ACTIONS[step])
        farms = observation.get("farms", []) or []
        player = int(observation.get("player", 0) or 0)
        farm = farms[player] if player < len(farms) else {{}}
        action = _align_hands(action, len(farm.get("hands", []) or []))
        return _repair(observation, action, step)
    except Exception:
        farms = observation.get("farms", []) or []
        player = int(observation.get("player", 0) or 0)
        farm = farms[player] if player < len(farms) else {{}}
        return {{
            "farmer": ["PASS"],
            "hands": [["PASS"] for _ in (farm.get("hands") or [])],
            "market": [],
        }}
'''


def build(actions: list, source_desc: str, out_path: str) -> None:
    content = TEMPLATE.format(actions_json=json.dumps(actions), source_desc=source_desc)
    with open(out_path, "w") as f:
        f.write(content)
